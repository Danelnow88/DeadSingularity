'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const rules=require('../js/experiments/dimensionRules.js');
const pursuit=require('../js/experiments/pursuit.js');
const intent={moveX:0,moveY:0},safe={};
const c=rules.create('museum-time');
let t;
for(let i=0;i<240;i++)t=c.sample(1/60,intent,safe);
assert(Math.abs(t.scale-.08)<1e-8);assert.equal(t.controlDt,1/60);
assert(t.combatDt>0&&t.combatDt<t.controlDt);
for(const reason of ['dashActive','dashWillStart','hardCC','externalForcedMove'])assert.equal(c.sample(.02,intent,{[reason]:true}).scale,1);
assert.equal(c.sample(0,intent,safe).combatDt,0);
c.reset();assert.equal(c.sample(.01,{moveX:1,moveY:0},safe).scale,1);
assert.deepEqual(rules.create('standard').sample(.02,intent,safe),{controlDt:.02,combatDt:.02,scale:1});
assert.throws(()=>rules.create('toroidal'));
const session=rules.session('museum-time');
assert.equal(session.healTicks(4.99),0);assert.equal(session.healTicks(.01),1);
session.enter(1);assert.equal(session.regen,0);assert.equal(session.ruleId,'museum-time');
session.enter(2);assert.equal(session.ruleId,'standard');
const p=pursuit.create('test:1'),e={enemyTypeId:'tank',hp:80,maxHp:100,damage:10,speed:40,hostileClass:'heavy'};
assert.throws(()=>pursuit.create(''));
assert(!p.provoke({...e,hp:NaN},0));assert(!p.provoke({...e,enemyTypeId:'unknown'},0));
assert(p.provoke(e,0));assert(!p.provoke(e,0));
e.hp=35;assert(p.depart(e,'cross-1'));assert(!p.depart(e,'cross-1'));
assert(p.entered(1));assert(!p.entered(1));
assert.deepEqual(p.reservations(),{hostiles:1,heavy:1});
assert(!p.tick(0));assert(!p.tick(2));assert(p.tick(.5));
const clone={};assert(p.placed(clone));assert.equal(clone.hp,35);assert.equal(clone.maxHp,100);
assert.equal(clone.pursuitUid,'test:1');assert.equal(p.reservations().hostiles,0);
assert(p.arrived());assert(!p.depart(clone,'cross-1'));
assert(p.depart(clone,'cross-2'));p.entered(2);p.tick(3);p.placed(clone);p.arrived();
assert(!p.depart(clone,'cross-3'));assert.equal(p.phase,'escaped');
const dead=pursuit.create('kill');dead.provoke(e,0);assert(dead.kill('kill'));assert(!dead.kill('kill'));dead.cancel('reset');assert.equal(dead.phase,'killed');
const timeout=pursuit.create('timeout');timeout.provoke(e,0);timeout.depart(e,'1');timeout.entered(1);assert(!timeout.tick(10.5));assert.equal(timeout.phase,'escaped');
const ctx={W:900,H:520,radius:20,view:{x:0,y:0,width:900,height:520},player:{x:450,y:260},enemies:[]};
assert(pursuit.position(ctx));assert(!pursuit.safePosition({x:450,y:260},ctx));
assert(!pursuit.safePosition({x:-1,y:260},ctx));
assert.equal(pursuit.position({...ctx,unsafe:()=>true}),null);
// Real projectile hurtbox: player can cross a nearly suspended bullet.
const box={window:{NV:{}},Math,Set,Map};vm.createContext(box);
vm.runInContext(fs.readFileSync('js/engine/bullets.js','utf8'),box);
const b={x:100,y:100,radius:5};
assert(!box.window.NV.hostileProjectileHitsPlayer(b,100,100,{x:130,y:100},20));
assert(box.window.NV.hostileProjectileHitsPlayer(b,100,100,{x:130,y:100},20,{x:70,y:100}));
// Recharge uses simulated time; dash distance and duration still use control time.
box.window.NV.BALANCE={DASH_REGEN_PER_SECOND:20,DASH_SPEED:400,DASH_DURATION:.2,DASH_RECHARGE_DELAY:.4};
vm.runInContext(fs.readFileSync('js/engine/movement.js','utf8'),box);
const resting={stun:0,dashActive:false,dashInputHeld:false,dashRechargeDelay:0,dashStamina:0,dashStaminaMax:100};
box.window.NV.updatePlayerDash(resting,false,0,0,0,0,false,.1,.01);assert.equal(resting.dashStamina,.2);
const legacy={...resting,dashStamina:0};box.window.NV.updatePlayerDash(legacy,false,0,0,0,0,false,.1);assert.equal(legacy.dashStamina,2);
const dashing={...resting,x:0,y:0,dashActive:true,dashDirX:1,dashDirY:0,dashTime:.2};
box.window.NV.updatePlayerDash(dashing,false,0,0,0,0,false,.1,.01);assert.equal(dashing.x,40);assert.equal(dashing.dashTime,.1);
console.log('PASS dimension_experiments: clocks, regen, relative sweep, transfers, reservations, identity, safe placement');
