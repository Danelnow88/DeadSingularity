'use strict';
const {app,BrowserWindow}=require('electron');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict');
app.setPath('userData',fs.mkdtempSync(path.join(os.tmpdir(),'ds-artillery-')));
const delay=ms=>new Promise(r=>setTimeout(r,ms));
app.whenReady().then(async()=>{
  const root=path.resolve(__dirname,'..'),out=path.join(root,'local/validation/artillery-cleanup');
  fs.mkdirSync(out,{recursive:true});
  const win=new BrowserWindow({show:false,width:1200,height:800,webPreferences:{offscreen:true,backgroundThrottling:false,contextIsolation:true,sandbox:true}});
  const errors=[];win.webContents.on('console-message',d=>{if(d.level==='error')errors.push(d.message);});
  const run=s=>win.webContents.executeJavaScript(s,true);
  await win.loadFile(path.join(root,'index.html'),{query:{fresh:'1',combatLab:'1'}});await delay(500);
  await run(`window.qaShots=0;window.qaEntities=[];window.qaFused=false;window.qaArt=NV.createWavePressure();
    const update=NV.updateEnemies;
    NV.updateEnemies=function(dt,st){const r=update(dt,st);window.qaEntities=st.enemies;
      window.qaFused ||= st.enemies.some(e=>e.fusionLevel>0);
      const count=st.bullets.length;
      NV.updateWavePressure(dt,{...st,state:window.qaArt,active:true,difficulty:'normal',wave:3,boss:null});
      window.qaShots+=st.bullets.length-count;return r;};
    NV.setFirePolicy('manual');true;`);
  const start=await run(`NV.combatLabRuntime.start({characterId:'rook',wave:3,difficultyId:'normal',durationMode:'infinite',composition:[{enemyId:'tank',quantity:6},{enemyId:'drone',quantity:8}]})`);
  assert(start.ok,JSON.stringify(start));await delay(3500);
  fs.writeFileSync(path.join(out,'playing.png'),(await win.webContents.capturePage()).toPNG());
  await run('NV.combatLabRuntime.pause()');
  const before=await run('JSON.stringify(window.qaArt)');await delay(200);assert.equal(await run('JSON.stringify(window.qaArt)'),before);
  fs.writeFileSync(path.join(out,'tanks.png'),(await win.webContents.capturePage()).toPNG());
  await run('NV.combatLabRuntime.resume();NV.setFirePolicy("legacy-auto");NV.input.setFire(true);');
  await delay(5000);
  const result=await run('({shots:window.qaShots,fused:window.qaFused,runtime:NV.getRuntimeSnapshot()})');
  assert(result.shots>0,'artillería no disparó');assert.equal(result.fused,false);assert.deepEqual(errors,[]);
  await run('NV.combatLabRuntime.reset()');assert.equal((await run('NV.getRuntimeSnapshot()')).enemies,0);
  fs.writeFileSync(path.join(out,'runtime.json'),JSON.stringify({pass:true,result,errors},null,2));
  console.log('PASS Electron: artillería física, pausa, grupos individuales, reset y sin errores');app.exit(0);
}).catch(e=>{console.error(e);app.exit(1);});
